-- Run this script in Supabase Dashboard -> SQL Editor.
-- It creates the server-side access-code inventory used by both sites.

create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.access_codes (
  id bigint generated by default as identity primary key,
  code text not null unique check (code = upper(code)),
  max_uses integer not null default 2 check (max_uses between 1 and 100),
  used_count integer not null default 0 check (used_count >= 0 and used_count <= max_uses),
  created_at timestamptz not null default now()
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  description text not null default '',
  type text not null default '低成本试跑',
  risk text not null default '先验证',
  tags text[] not null default '{}',
  resource_url text,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  rating smallint check (rating between 1 and 5),
  message text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists access_codes_created_at_idx on public.access_codes (created_at desc);
create index if not exists projects_published_idx on public.projects (is_published);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = auth.uid()
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

alter table public.admin_users enable row level security;
alter table public.access_codes enable row level security;
alter table public.projects enable row level security;
alter table public.feedback enable row level security;

drop policy if exists "admins can read access codes" on public.access_codes;
create policy "admins can read access codes"
on public.access_codes for select
to authenticated
using (public.is_admin());

drop policy if exists "admins can manage projects" on public.projects;
create policy "admins can manage projects"
on public.projects for all
to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "public can read published projects" on public.projects;
create policy "public can read published projects"
on public.projects for select
to anon, authenticated
using (is_published = true);

drop policy if exists "anyone can submit feedback" on public.feedback;
create policy "anyone can submit feedback"
on public.feedback for insert
to anon, authenticated
with check (rating is null or rating between 1 and 5);

create or replace function public.redeem_access_code(p_code text)
returns table (code text, remaining_uses integer)
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  update public.access_codes
  set used_count = used_count + 1
  where access_codes.code = upper(trim(p_code))
    and used_count < max_uses
  returning code, max_uses - used_count;
end;
$$;

revoke all on function public.redeem_access_code(text) from public;
grant execute on function public.redeem_access_code(text) to anon, authenticated;

create or replace function public.generate_access_codes(
  p_count integer default 10,
  p_prefix text default 'TRY',
  p_max_uses integer default 2
)
returns setof public.access_codes
language plpgsql
security definer
set search_path = public
as $$
declare
  requested_count integer := least(greatest(coalesce(p_count, 1), 1), 500);
  prefix_value text := upper(regexp_replace(coalesce(p_prefix, 'TRY'), '[^A-Z0-9]', '', 'g'));
  i integer;
  new_code text;
begin
  if not public.is_admin() then
    raise exception 'admin access required' using errcode = '42501';
  end if;

  prefix_value := left(case when prefix_value = '' then 'TRY' else prefix_value end, 8);

  for i in 1..requested_count loop
    loop
      new_code := prefix_value || upper(encode(gen_random_bytes(6), 'hex'));
      exit when not exists (
        select 1 from public.access_codes where access_codes.code = new_code
      );
    end loop;

    insert into public.access_codes (code, max_uses)
    values (new_code, least(greatest(coalesce(p_max_uses, 2), 1), 100));
  end loop;

  return query
  select * from public.access_codes
  where created_at >= now() - interval '1 minute'
    and code like prefix_value || '%'
  order by created_at desc;
end;
$$;

revoke all on function public.generate_access_codes(integer, text, integer) from public;
grant execute on function public.generate_access_codes(integer, text, integer) to authenticated;

